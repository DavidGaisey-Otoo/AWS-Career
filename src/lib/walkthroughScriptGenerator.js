/**
 * walkthroughScriptGenerator.js — PJ-02 Full Unified Script Generator.
 *
 * Given a Deep Walkthrough, produces complete end-to-end output in 4
 * formats by concatenating + decorating per-step snippets:
 *
 *   - Console Step-by-Step Guide (Markdown — PDF-ready)
 *   - Full CLI Bash Script (.sh)
 *   - Full CloudFormation Template (.yaml)
 *   - Full Terraform Configuration (.tf)
 *
 * Each generator extracts placeholders, hoists them into a clear
 * variables / parameters section, and adds explanatory comments.
 *
 * Separate from the existing `scriptGenerator.js` (which generates from
 * analyzed service lists) — this one builds from Deep Walkthrough steps.
 */

// Extract UPPER_SNAKE_CASE placeholders that look like user-supplied values
function extractPlaceholders(text) {
  if (!text) return [];
  const matches = text.match(/\b[A-Z][A-Z0-9_]{2,}\b/g) || [];
  // Filter out service names + acronyms — those aren't placeholders
  const noise = new Set([
    'AWS', 'YAML', 'JSON', 'HCL', 'HTTPS', 'HTTP', 'TLS', 'TCP', 'UDP', 'DNS', 'CIDR',
    'AZ', 'AZS', 'VPC', 'IGW', 'NAT', 'ALB', 'NLB', 'IAM', 'ARN', 'OAC', 'OAI',
    'ID', 'GET', 'POST', 'PUT', 'DELETE', 'EOF', 'README', 'NULL', 'TRUE', 'FALSE',
    'IPV4', 'IPV6', 'SSL', 'SSH', 'API', 'CDN', 'OK',
    'CIDRIP', 'CDK', 'SDK', 'CLI', 'CFN', 'TF', 'SAM',
    'TLSV1', 'SNI', 'RFC', 'BGP', 'CRC', 'JIT',
    'EBS', 'EC2', 'S3', 'RDS', 'KMS', 'ECS', 'EKS', 'ECR', 'SQS', 'SNS',
    'WAF', 'CRR', 'SRR', 'PITR', 'DLQ', 'ENI', 'VGW', 'DX', 'TGW',
    'ELB', 'CFN', 'EFS', 'EMR', 'DAX', 'STS', 'XKS', 'SDDC', 'CSI', 'ACL',
  ]);
  return [...new Set(matches.filter((m) => !noise.has(m) && m.length >= 4))];
}

function escapeYaml(s) {
  return String(s).replace(/[\r\n]/g, ' ');
}

function toTitle(s) {
  return String(s).split(/[_\-\s]+/).map((p) => p.charAt(0).toUpperCase() + p.slice(1).toLowerCase()).join('');
}

