// 4. Full Terraform Configuration (.tf)
// ════════════════════════════════════════════════════════════════════
export function generateTerraform(w, opts = {}) {
  const region = opts.region || 'us-east-1';
  const allTf = (w.steps || []).map((s) => s.how?.tf || '').join('\n');
  const placeholders = extractPlaceholders(allTf);
  const missingSteps = (w.steps || []).filter((step) => !step.how?.tf);
  const blocked = placeholders.length > 0 || missingSteps.length > 0;

  const lines = [];
  lines.push('# ============================================================');
  lines.push(`# ${w.title}`);
  lines.push(`# ${w.blurb}`);
  lines.push('# Generated by AWS Career Launchpad Pro · PJ-02 Script Generator');
  lines.push(`# Target AWS region: ${region}   ← AD-01 Smart Region Suggestion`);
  lines.push('# REVIEW + EDIT before terraform apply — generated by concatenating per-step snippets.');
  lines.push('# ============================================================');
  lines.push('');

  if (blocked) {
    lines.push('# DEPLOYMENT BLOCKED: incomplete walkthrough export.');
    lines.push('variable "confirm_generated_artifact_complete" {');
    lines.push('  type    = bool');
    lines.push('  default = false');
    lines.push('}');
    lines.push('resource "terraform_data" "generation_safety_gate" {');
    lines.push('  lifecycle {');
    lines.push('    precondition {');
    lines.push('      condition = var.confirm_generated_artifact_complete');
    lines.push(`      error_message = "Resolve missing Terraform steps (${missingSteps.map((step) => step.number).join(', ') || 'none'}) and all placeholders before apply."`);
    lines.push('    }');
    lines.push('  }');
    lines.push('}');
    lines.push('');
  }
  lines.push('terraform {');
  lines.push('  required_version = ">= 1.5.0"');
  lines.push('  required_providers {');
  lines.push('    aws = { source = "hashicorp/aws", version = "~> 5.0" }');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push('# Primary region — picked by AD-01 region suggester · override via TF_VAR_aws_region or -var');
  lines.push('variable "aws_region" {');
  lines.push('  type    = string');
  lines.push(`  default = "${region}"`);
  lines.push('}');
  lines.push('');
  lines.push('provider "aws" {');
  lines.push('  region = var.aws_region');
  lines.push('}');
  lines.push('');

  if (placeholders.length > 0) {
    lines.push('# ----------------------------------------------------------');
    lines.push('# Variables — set these in terraform.tfvars or via -var flags');
    lines.push('# ----------------------------------------------------------');
    placeholders.forEach((p) => {
      lines.push(`variable "${p.toLowerCase()}" {`);
      lines.push(`  type        = string`);
      lines.push(`  description = "Replace with your ${p} value"`);
      lines.push(`  default     = "REPLACE_${p}"`);
      lines.push('}');
      lines.push('');
    });
  }

  w.steps.forEach((s) => {
    lines.push('# ============================================================');
    lines.push(`# Step ${s.number} — ${s.title}`);
    lines.push(`# ${s.what || ''}`);
    lines.push('# ============================================================');
    if (s.mistakes?.length) {
      lines.push('# Heads up:');
      s.mistakes.forEach((m) => lines.push(`#   ⚠ ${m.replace(/[\r\n]/g, ' ')}`));
    }
    lines.push('');
    if (s.how?.tf) {
      lines.push(s.how.tf.trim());
    } else {
      lines.push(`# (no Terraform snippet for this step — see CLI or Console)`);
    }
    lines.push('');
  });

  return lines.join('\n');
}

