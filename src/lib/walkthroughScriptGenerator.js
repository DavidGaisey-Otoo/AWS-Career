// 1. Console Step-by-Step Guide (Markdown — PDF-ready)
// ════════════════════════════════════════════════════════════════════
export function generateConsoleGuide(w, opts = {}) {
  const region = opts.region;
  const lines = [];
  lines.push(`# ${w.title}`);
  lines.push('');
  lines.push(`> ${w.blurb}`);
  lines.push('');
  lines.push(`**Estimated time:** ${w.estMinutes} minutes  `);
  lines.push(`**Difficulty:** ${w.difficulty}  `);
  lines.push(`**Services used:** ${(w.services || []).join(', ').toUpperCase()}`);
  if (region) lines.push(`**Target AWS region:** ${region} _(picked by AD-01 region suggester)_`);
  lines.push('');
  lines.push(`_Generated by AWS Career Launchpad Pro · PJ-02 Script Generator_`);
  lines.push('');

  if (w.prereqs?.length) {
    lines.push('## Prerequisites');
    lines.push('');
    w.prereqs.forEach((p) => lines.push(`- ${p}`));
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push('## Step-by-step guide');
  lines.push('');

  w.steps.forEach((s) => {
    lines.push(`### Step ${s.number} — ${s.title}`);
    lines.push('');
    if (s.what) { lines.push(`**What:** ${s.what}`); lines.push(''); }
    if (s.why)  { lines.push(`**Why it matters:**`); lines.push(''); lines.push(s.why.trim()); lines.push(''); }
    if (s.analogy) { lines.push(`> _Analogy:_ ${s.analogy}`); lines.push(''); }
    if (s.mistakes?.length) {
      lines.push('**Common mistakes to avoid:**');
      lines.push('');
      s.mistakes.forEach((m) => lines.push(`- ⚠ ${m}`));
      lines.push('');
    }
    if (s.how?.console?.length) {
      lines.push('**Console actions:**');
      lines.push('');
      s.how.console.forEach((c, i) => lines.push(`${i + 1}. ${c}`));
      lines.push('');
    }
    lines.push('---');
    lines.push('');
  });

  lines.push('## You\'re done!');
  lines.push('');
  lines.push(`If every step is complete you\'ve successfully built **${w.title}**.`);
  lines.push('');
  lines.push('Don\'t forget to clean up unused resources to avoid ongoing charges.');

  return lines.join('\n');
}

