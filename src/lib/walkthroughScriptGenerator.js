// 2. Full CLI Bash Script (.sh)
// ════════════════════════════════════════════════════════════════════
export function generateCliScript(w, opts = {}) {
  const region = opts.region || 'us-east-1';
  const allText = (w.steps || []).map((s) => s.how?.cli || '').join('\n');
  const placeholders = extractPlaceholders(allText);
  const missingSteps = (w.steps || []).filter((step) => !step.how?.cli);

  const lines = [];
  lines.push('#!/usr/bin/env bash');
  lines.push('# ============================================================');
  lines.push(`# ${w.title}`);
  lines.push(`# ${w.blurb}`);
  lines.push('# Generated by AWS Career Launchpad Pro · PJ-02 Script Generator');
  lines.push(`# Target AWS region: ${region}   ← AD-01 Smart Region Suggestion`);
  lines.push('# Review every TODO before running. AWS resources cost money.');
  lines.push('# ============================================================');
  lines.push('');
  lines.push('# Stop on first error, treat unset vars as errors, fail on pipe errors');
  lines.push('set -euo pipefail');
  lines.push('');

  if (placeholders.length || missingSteps.length) {
    lines.push('echo "DEPLOYMENT BLOCKED: this walkthrough export is an incomplete draft." >&2');
    lines.push(`echo "Missing CLI steps: ${missingSteps.map((step) => step.number).join(', ') || 'none'}; placeholders: ${placeholders.join(', ') || 'none'}" >&2`);
    lines.push('echo "Resolve every item and remove this gate only after review." >&2');
    lines.push('exit 1');
    lines.push('');
  }

  if (placeholders.length > 0) {
    lines.push('# ---------- VARIABLES (edit these before running) ----------');
    placeholders.forEach((p) => {
      lines.push(`${p}="REPLACE_WITH_YOUR_VALUE"   # TODO: set this`);
    });
    lines.push('# -----------------------------------------------------------');
    lines.push('');
  }

  lines.push('# Common AWS settings');
  lines.push(`AWS_REGION="\${AWS_REGION:-${region}}"   # picked by AD-01 region suggester · override via export AWS_REGION=us-east-1`);
  lines.push('echo "Running in region: $AWS_REGION"');
  lines.push('');

  w.steps.forEach((s) => {
    lines.push('# ============================================================');
    lines.push(`# Step ${s.number} — ${s.title}`);
    lines.push(`# ${(s.what || '').replace(/[\r\n]/g, ' ')}`);
    lines.push('# ============================================================');
    if (s.mistakes?.length) {
      lines.push('# Heads up:');
      s.mistakes.forEach((m) => lines.push(`#   ⚠ ${m.replace(/[\r\n]/g, ' ')}`));
    }
    lines.push('');
    if (s.how?.cli) {
      lines.push(s.how.cli.trim());
    } else {
      lines.push(`# (no CLI snippet for this step — perform via console:`);
      (s.how?.console || []).forEach((c) => lines.push(`#   • ${c}`));
      lines.push(')');
    }
    lines.push('');
    lines.push(`echo "✓ Step ${s.number} done"`);
    lines.push('');
  });

  lines.push('# ============================================================');
  lines.push('echo "🎉 All steps complete — verify in the AWS Console!"');
  lines.push('# ============================================================');

  return lines.join('\n');
}

