// 3. Full CloudFormation Template (.yaml)
// ════════════════════════════════════════════════════════════════════
export function generateCfnTemplate(w, opts = {}) {
  const region = opts.region;
  const allCfn = (w.steps || []).map((s) => s.how?.cfn || '').join('\n');
  const placeholders = extractPlaceholders(allCfn);
  const missingSteps = (w.steps || []).filter((step) => !step.how?.cfn);
  const blocked = placeholders.length > 0 || missingSteps.length > 0;

  const lines = [];
  lines.push('AWSTemplateFormatVersion: "2010-09-09"');
  lines.push(`Description: |`);
  lines.push(`  ${w.title}`);
  lines.push(`  ${w.blurb}`);
  lines.push('  Generated by AWS Career Launchpad Pro · PJ-02 Script Generator.');
  if (region) lines.push(`  Target AWS region: ${region} (AD-01 suggested — deploy with: aws cloudformation deploy --region ${region} ...)`);
  lines.push('  REVIEW + EDIT before deploying — assembled by concatenating per-step snippets.');
  lines.push('');

  if (placeholders.length > 0 || blocked) {
    lines.push('Parameters:');
    placeholders.forEach((p) => {
      lines.push(`  ${toTitle(p)}:`);
      lines.push(`    Type: String`);
      lines.push(`    Description: "Replace with your ${p} value"`);
      lines.push(`    Default: "REPLACE_${p}"`);
    });
    if (blocked) {
      lines.push('  ConfirmGeneratedArtifactComplete:');
      lines.push('    Type: String');
      lines.push('    Default: "BLOCKED"');
      lines.push('    AllowedValues: ["BLOCKED", "REVIEWED"]');
      lines.push('    Description: "Set REVIEWED only after implementing every missing step and placeholder."');
    }
    lines.push('');
  }

  if (blocked) {
    lines.push('Rules:');
    lines.push('  GeneratedArtifactSafetyGate:');
    lines.push('    Assertions:');
    lines.push('      - Assert: !Equals [!Ref ConfirmGeneratedArtifactComplete, "REVIEWED"]');
    lines.push(`        AssertDescription: "Incomplete walkthrough export. Missing CFN steps: ${missingSteps.map((step) => step.number).join(', ') || 'none'}."`);
    lines.push('');
  }

  lines.push('# ============================================================');
  lines.push('# Resources — merged from each step\'s CFN snippet');
  lines.push('# Note: some snippets in the Deep Walkthrough are illustrative');
  lines.push('# fragments. Review references + cross-stack dependencies before');
  lines.push('# running `aws cloudformation deploy`.');
  lines.push('# ============================================================');
  lines.push('Resources:');
  lines.push('');

  w.steps.forEach((s) => {
    lines.push(`  # ----- Step ${s.number}: ${escapeYaml(s.title)} -----`);
    lines.push(`  # ${escapeYaml(s.what || '')}`);
    if (s.how?.cfn) {
      const snippet = s.how.cfn.trim();
      const cleaned = snippet
        .replace(/^Resources:\s*\n?/gmi, '')
        .replace(/^Parameters:\s*\n?/gmi, '# (parameters hoisted to top)\n');
      const linesIn = cleaned.split('\n');
      linesIn.forEach((line) => {
        if (line.trim().length === 0) { lines.push(''); return; }
        lines.push('  ' + line);
      });
    } else {
      lines.push(`  # (no CloudFormation snippet for this step — manual / CLI only)`);
    }
    lines.push('');
  });

  lines.push('Outputs:');
  lines.push('  Note:');
  lines.push('    Description: "Assembled from per-step snippets — verify references before deploy"');
  lines.push('    Value: "REVIEW + VALIDATE before deploy"');

  return lines.join('\n');
}

