/**
 * deliverableGenerator.js — turns a project analysis into actual client
 * deliverables (proposal, contract, invoice, architecture, slides, package).
 *
 * Each generator returns a Markdown string. Pair with downloadMarkdownFile()
 * or downloadPdfFile() in printableHtml.js to ship to the user as a file.
 *
 * Used by:
 *   • MasterIntelligencePanel.Panel7Actions (action buttons)
 *   • Job Analyzer follow-up deliverables
 *   • Project Builder report stage
 *
 * Backed by REAL data (the analysis the engine produced), never lorem ipsum.
 */

function moneyFmt(n, currency = 'USD') {
  if (n == null) return '—';
  const symbol = currency === 'GBP' ? '£' : currency === 'EUR' ? '€' : '$';
  return `${symbol}${Number(n).toLocaleString()}`;
}

function todayLong() {
  return new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
}

function dueDateFromTimeline(timeline) {
  if (!timeline) return null;
  const m = timeline.match(/(\d+)\s+(day|week|month)/i);
  if (!m) return null;
  const n = parseInt(m[1], 10);
  const unit = m[2].toLowerCase();
  const ms = unit === 'day' ? 86400000 : unit === 'week' ? 604800000 : 2592000000;
  const d = new Date(Date.now() + n * ms);
  return d.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
}

// ──────────────────────────────────────────────────────────────────────
// PROPOSAL
// ──────────────────────────────────────────────────────────────────────

export function generateProposalMd(analysis) {
  const lines = [];
  const client = analysis.client || '[Client]';
  const region = analysis.region || 'us-east-1';
  const total = analysis.budget?.fixed ? moneyFmt(analysis.budget.fixed, analysis.budget.currency) : '[To be agreed]';
  const timeline = analysis.timeline || '[To be agreed]';

  lines.push(`# Proposal — AWS Infrastructure Project`);
  lines.push('');
  lines.push(`**To:** ${client}`);
  lines.push(`**Date:** ${todayLong()}`);
  lines.push(`**Project total:** ${total}`);
  lines.push(`**Timeline:** ${timeline}`);
  if (analysis.compliance?.length) {
    lines.push(`**Compliance:** ${analysis.compliance.map((c) => c.label).join(', ')}`);
  }
  lines.push('');

  lines.push(`## Executive summary`);
  lines.push('');
  lines.push(`${analysis.summary}`);
  if (analysis.urgency === 'critical') {
    lines.push('');
    lines.push(`> ⚡ I can begin within **48 hours** given the urgency stated in your brief.`);
  }
  lines.push('');

  if (analysis.compliance?.length) {
    lines.push(`## Compliance approach`);
    lines.push('');
    for (const c of analysis.compliance) lines.push(`- **${c.label}** — addressed via ${c.addServices?.join(', ') || 'controls below'}`);
    lines.push('');
  }

  lines.push(`## Architecture (${analysis.services?.length || 0} services)`);
  lines.push('');
  lines.push(`Region: \`${region}\` · Deployment: \`${(analysis.deploymentMethods || ['terraform']).join('/').toUpperCase()}\``);
  lines.push('');
  lines.push('| Service | Category | Cost note |');
  lines.push('|---|---|---|');
  for (const s of analysis.services || []) {
    lines.push(`| ${s.label} | ${s.category} | ${s.costNote || '—'} |`);
  }
  lines.push('');

  lines.push(`## Approach`);
  lines.push('');
  if (analysis.approach) {
    for (const line of analysis.approach) {
      lines.push(`### ${line.heading}`);
      lines.push('');
      if (Array.isArray(line.body)) {
        line.body.forEach((b, i) => lines.push(`${i + 1}. ${b}`));
      } else {
        lines.push(line.body);
      }
      lines.push('');
    }
  }

  lines.push(`## Deliverables`);
  lines.push('');
  lines.push(`- Working AWS infrastructure in \`${region}\``);
  lines.push(`- Complete ${(analysis.deploymentMethods || ['terraform']).join(' + ').toUpperCase()} source code`);
  lines.push(`- Architecture diagram (PDF)`);
  lines.push(`- Runbook + handover documentation`);
  lines.push(`- 1-hour handover call`);
  lines.push(`- 7 days post-launch support`);
  lines.push('');

  lines.push(`## Investment`);
  lines.push('');
  lines.push(`| Item | Amount |`);
  lines.push(`|---|---:|`);
  lines.push(`| Project total (fixed) | ${total} |`);
  if (analysis.budget?.awsMonthly) {
    lines.push(`| Client monthly AWS spend (estimated) | ≤ ${moneyFmt(analysis.budget.awsMonthly, analysis.budget?.currency)} |`);
  }
  lines.push('');
  lines.push(`Payment terms: 50% deposit on acceptance, 50% on delivery.`);
  lines.push('');

  lines.push(`## Next step`);
  lines.push('');
  lines.push(`Reply "accepted" with PO number — I begin within 48 hours.`);
  lines.push('');
  lines.push('---');
  lines.push('_Generated by AWS Career Launchpad Pro_');
  return lines.join('\n');
}

