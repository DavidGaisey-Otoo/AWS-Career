// INVOICE
// ──────────────────────────────────────────────────────────────────────

export function generateInvoiceMd(analysis) {
  const client = analysis.client || '[Client]';
  const total = analysis.budget?.fixed ?? 0;
  const currency = analysis.budget?.currency || 'USD';
  const deposit = Math.round(total * 0.5 * 100) / 100;
  const symbol = currency === 'GBP' ? '£' : currency === 'EUR' ? '€' : '$';
  const due = dueDateFromTimeline('14 days') || '14 days from issue';

  return [
    `# Invoice`,
    '',
    `**Invoice #:** INV-${Date.now().toString().slice(-6)}`,
    `**Date issued:** ${todayLong()}`,
    `**Due:** ${due}`,
    '',
    `**Bill to:** ${client}`,
    '',
    `## Line items`,
    '',
    `| Description | Amount |`,
    `|---|---:|`,
    `| Initial deposit — AWS infrastructure project (50%) | ${symbol}${deposit.toLocaleString()} |`,
    `| **TOTAL DUE** | **${symbol}${deposit.toLocaleString()}** |`,
    '',
    `## Payment details`,
    '',
    `Account name: [Your name]`,
    `Account number: [XXXX XXXX]`,
    `Sort code / IBAN: [XXX]`,
    `Reference: INV-${Date.now().toString().slice(-6)}`,
    '',
    `## Notes`,
    '',
    `- The remaining 50% (${symbol}${deposit.toLocaleString()}) is due on delivery acceptance.`,
    `- Client AWS account costs are billed separately by AWS directly to ${client}.`,
    '',
    '---',
    '_Generated by AWS Career Launchpad Pro_',
  ].join('\n');
}

// ──────────────────────────────────────────────────────────────────────
// ARCHITECTURE (with ASCII diagram)
// ──────────────────────────────────────────────────────────────────────

export function generateArchitectureMd(analysis) {
  const services = analysis.services || [];
  const byCat = {};
  for (const s of services) {
    if (!byCat[s.category]) byCat[s.category] = [];
    byCat[s.category].push(s);
  }

  // Very simple text-diagram per category
  const diagram = [];
  diagram.push('┌────────────────────────────────────────────────────────────┐');
  diagram.push('│  USERS                                                     │');
  diagram.push('└────────────────────────────┬───────────────────────────────┘');
  diagram.push('                             ▼');
  if (byCat.network?.some((s) => s.id === 'route53'))    diagram.push('                       Route 53 (DNS)');
  if (byCat.network?.some((s) => s.id === 'cloudfront')) diagram.push('                       CloudFront (CDN + HTTPS)');
  if (byCat.security?.some((s) => s.id === 'waf'))       diagram.push('                       WAF (firewall)');
  diagram.push('                             ▼');
  if (byCat.network?.some((s) => s.id === 'alb'))        diagram.push('                       Application Load Balancer');
  if (byCat.compute?.length) {
    diagram.push('  ┌──────────────────────────┴──────────────────────────┐');
    diagram.push('  ▼                                                     ▼');
    diagram.push(`  COMPUTE: ${byCat.compute.map((s) => s.label).join(' / ')}`);
  }
  if (byCat.database?.length) {
    diagram.push('                             ▼');
    diagram.push(`  DATABASE: ${byCat.database.map((s) => s.label).join(' / ')}`);
  }
  if (byCat.storage?.length) {
    diagram.push(`  STORAGE:  ${byCat.storage.map((s) => s.label).join(' / ')}`);
  }
  if (byCat.security?.length) {
    diagram.push(`  SECURITY: ${byCat.security.map((s) => s.label).join(' / ')}`);
  }
  if (byCat.monitoring?.length) {
    diagram.push(`  OBSERVABILITY: ${byCat.monitoring.map((s) => s.label).join(' / ')}`);
  }

  const lines = [];
  lines.push(`# Architecture — ${analysis.client || 'Project'}`);
  lines.push('');
  lines.push(`**Region:** ${analysis.region || 'TBA'} · **Date:** ${todayLong()}`);
  lines.push('');
  lines.push('## Diagram');
  lines.push('');
  lines.push('```');
  lines.push(diagram.join('\n'));
  lines.push('```');
  lines.push('');
  lines.push('## Services');
  lines.push('');
  for (const [cat, items] of Object.entries(byCat)) {
    lines.push(`### ${cat.toUpperCase()}`);
    lines.push('');
    for (const s of items) {
      lines.push(`- **${s.label}** — ${s.desc}`);
    }
    lines.push('');
  }
  lines.push('---');
  lines.push('_Generated by AWS Career Launchpad Pro_');
  return lines.join('\n');
}

// ──────────────────────────────────────────────────────────────────────
// SLIDES (Markdown outline)
// ──────────────────────────────────────────────────────────────────────

export function generateSlidesMd(analysis) {
  const lines = [];
  lines.push(`# Slides — ${analysis.client || 'Project'} pitch deck`);
  lines.push('');
  lines.push('## Slide 1 — Title');
  lines.push(`**${analysis.client || 'Client'} — AWS migration & deployment**`);
  lines.push(`Prepared by [Your name] · ${todayLong()}`);
  lines.push('');
  lines.push('## Slide 2 — The challenge');
  lines.push(analysis.summary);
  lines.push('');
  lines.push('## Slide 3 — Proposed architecture');
  lines.push(`${(analysis.services || []).length} AWS services · Region ${analysis.region || 'TBA'}`);
  for (const s of (analysis.services || []).slice(0, 6)) lines.push(`- ${s.label}`);
  lines.push('');
  lines.push('## Slide 4 — Compliance');
  if (analysis.compliance?.length) {
    for (const c of analysis.compliance) lines.push(`- ${c.label}`);
  } else lines.push('- Standard AWS best-practice security baseline');
  lines.push('');
  lines.push('## Slide 5 — Timeline');
  lines.push(`Total: ${analysis.timeline || 'TBA'} · 30% setup · 50% build · 20% test + handover`);
  lines.push('');
  lines.push('## Slide 6 — Investment');
  lines.push(`Project: ${analysis.budget?.fixed ? moneyFmt(analysis.budget.fixed, analysis.budget?.currency) : 'TBA'}`);
  lines.push(`AWS monthly: ≤ ${analysis.budget?.awsMonthly ? moneyFmt(analysis.budget.awsMonthly, analysis.budget?.currency) : 'TBA'}`);
  lines.push('');
  lines.push('## Slide 7 — Next step');
  lines.push(`Approve to begin within 48 hours.`);
  lines.push('');
  lines.push('---');
  lines.push('_Generated by AWS Career Launchpad Pro_');
  return lines.join('\n');
}

