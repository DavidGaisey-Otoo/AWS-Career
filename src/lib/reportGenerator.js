/**
 * Trigger a Markdown file download in the browser.
 */
export function downloadMarkdown(markdown, filename) {
  const blob = new Blob([markdown], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename || 'report.md';
  a.click();
  URL.revokeObjectURL(url);
}

/**
 * Open the print-friendly HTML in a new tab — user prints to PDF from there.
 */
export function openReportPrintable({ markdown, title, meta }) {
  return openPrintable({ markdown, title, meta });
}

/**
 * BF-07: Download a TRUE .pdf file directly to the user's Downloads folder.
 * No popup. No print dialog. Just click → file lands.
 * Uses html2pdf.js under the hood (lazy-loaded).
 */
export async function downloadReportAsPdf({ markdown, title, meta }) {
  return downloadPdfFile({ markdown, title, meta });
}

/**
 * Push a fresh portfolio repo containing README.md + REPORT.md + any
 * deliverables the caller hands us. Returns the public repo URL.
 */
export async function pushSessionReportToGitHub({
  token,
  input,
  repoName: explicitName,
  isPublic = true,
  topics = ['aws', 'portfolio', 'launchpad-pro'],
  extraDeliverables = [],
}) {
  const reportMd = buildSessionReportMarkdown(input);
  const readmeMd = buildProjectReadme(input);
  const repoName = explicitName || suggestRepoName(input.values?.projectName || input.session?.title || 'aws-project');

  const files = [
    { path: 'README.md',  content: readmeMd },
    { path: 'REPORT.md',  content: reportMd },
    { path: '.gitignore', content: defaultGitignore() },
    ...extraDeliverables,
  ];

  return pushPortfolioRepo({
    token,
    repoName,
    description: (input.values?.summary || input.session?.title || 'AWS portfolio project').slice(0, 340),
    isPublic,
    topics,
    files,
  });
}

function defaultGitignore() {
  return [
    'node_modules/',
    '.DS_Store',
    '.env',
    '.env.local',
    '.env.*.local',
    'dist/',
    'build/',
    '*.log',
    '.vscode/',
    '.idea/',
    'coverage/',
    '',
  ].join('\n');
}

function friendlyKey(k) {
  return k
    .replace(/([A-Z])/g, ' $1')
    .replace(/^./, (c) => c.toUpperCase())
    .replace(/[_-]/g, ' ');
}
