/**
 * BrandIcons.jsx — GitHub / LinkedIn / YouTube marks.
 *
 * lucide-react v1 removed every brand icon (trademark reasons), so these
 * three disappeared from the library the app had been importing them
 * from. They are still needed: the GitHub integration, the branding
 * engine and the learning video links all point at real services.
 *
 * These are lucide's own v0 paths, kept on lucide's geometry (24x24,
 * stroke-based, currentColor) and its prop API — `size`, `className`,
 * `strokeWidth` — so they remain drop-in wherever a lucide icon was used.
 */

function BrandIcon({ size = 24, strokeWidth = 2, className = '', children, ...rest }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      {...rest}
    >
      {children}
    </svg>
  );
}

